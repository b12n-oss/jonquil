;; Temporary probe for the endless-output test on the CI runner. Not for merge.
(require '[clojure.java.io :as io] '[jolt.process :as p])
(def t0 (System/currentTimeMillis))
(defn t [] (- (System/currentTimeMillis) t0))
(defn say [& xs] (println (apply str "[probe " (t) " ms] " (interpose " " xs))) (flush))
(let [dir (io/file (System/getProperty "java.io.tmpdir") (str "probe-" t0))
      _ (.mkdirs dir)
      sh (io/file dir "shell")
      tmp (java.io.File/createTempFile "probe-" ".out")]
  (spit sh "#!/bin/sh\nexec yes jonquil-probe-777\n")
  (.setExecutable sh true)
  (say "df /tmp:" (:out (p/sh "sh" "-c" "df -h /tmp | tail -1")))
  (say "nproc:" (:out (p/sh "nproc")))
  (let [proc (p/process {:in (io/file "/dev/null") :out tmp :err :discard} (.getPath sh) "-ilc" "true")]
    (say "started")
    (dotimes [i 8]
      (let [a (t)
            r (deref proc 100 ::running)
            b (t)
            len (.length tmp)
            c (t)]
        (say "poll" i "deref took" (- b a) "ms ->" (if (= r ::running) "running" (str "exit " (:exit r)))
             "| length" len "took" (- c b) "ms")))
    (say "pgrep before kill:" (pr-str (:out (p/sh "pgrep" "-fl" "jonquil-probe-777"))))
    (let [jp (:proc proc)
          a (t)
          kids (try (vec (.descendants (.toHandle jp))) (catch Throwable e (say "descendants threw" (str e)) []))]
      (say "descendants:" (count kids) "took" (- (t) a) "ms; alive?" (try (.isAlive jp) (catch Throwable e (str e))))
      (let [a (t)] (try (p/destroy-tree proc) (catch Throwable e (say "destroy-tree threw" (str e)))) (say "destroy-tree took" (- (t) a) "ms"))
      (let [a (t) r (deref proc 300 ::running)] (say "deref after TERM took" (- (t) a) "ms ->" (if (= r ::running) "STILL RUNNING" (str "exit " (:exit r))))
        (when (= r ::running)
          (let [a (t)] (try (.destroyForcibly jp) (catch Throwable e (say "destroyForcibly threw" (str e)))) (say "destroyForcibly took" (- (t) a) "ms"))
          (let [r2 (deref proc 2000 ::running)] (say "after KILL ->" (if (= r2 ::running) "STILL RUNNING" (str "exit " (:exit r2))))))))
    (Thread/sleep 300)
    (say "pgrep after kill:" (pr-str (:out (p/sh "pgrep" "-fl" "jonquil-probe-777"))))
    (say "final length" (.length tmp))
    (p/sh "pkill" "-9" "-f" "jonquil-probe-777")
    (.delete tmp)
    (say "df /tmp after:" (:out (p/sh "sh" "-c" "df -h /tmp | tail -1")))))
(System/exit 0)
